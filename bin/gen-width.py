#!/usr/bin/env python3
"""Generate go/width_table.go from Python's unicodedata.

The Go renderer must measure columns exactly as the Python one does, or the
parity harness compares two different notions of "width" and every wrapping
diff becomes ambiguous. Go's own `unicode.Mn` is *not* the same set as
`unicodedata.combining(ch) != 0`, so the table is generated from the
reference implementation rather than approximated from Go's tables.

    python3 bin/gen-width.py > go/width_table.go
"""

import sys
import unicodedata

MAX = 0x110000


def ranges(predicate):
    out = []
    start = None
    for cp in range(MAX):
        hit = predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_zero(cp):
    return unicodedata.combining(chr(cp)) != 0


def is_wide(cp):
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs, out):
    out.write("var %s = []rrange{\n" % name)
    for lo, hi in rs:
        out.write("\t{0x%04X, 0x%04X},\n" % (lo, hi))
    out.write("}\n\n")


def main():
    out = sys.stdout
    out.write('''// Code generated by bin/gen-width.py. DO NOT EDIT.
//
// Sourced from Python's unicodedata (%s), so the Go renderer and the
// Python reference implementation agree on display width to the codepoint.

package main

type rrange struct{ lo, hi rune }

func inRanges(r rune, rs []rrange) bool {
	lo, hi := 0, len(rs)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < rs[mid].lo:
			hi = mid - 1
		case r > rs[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

''' % unicodedata.unidata_version)
    emit("zeroWidth", ranges(is_zero), out)
    emit("wideWidth", ranges(is_wide), out)


if __name__ == "__main__":
    main()
