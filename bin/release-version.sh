#!/bin/sh
# Seal the version files on a release branch, in one step.
#
# The release flow runs three commands in this order:
#
#   git-ops-2 release minor   cuts release/0.3.0, pushes it, switches you onto it
#   sh bin/release-version.sh this script: rewrites, rebuilds, commits, pushes
#   git-ops-2 ship release/0.3.0 opens + merges the PRs, creates the GitHub release
#
# `release` computes the version from the latest GitHub release, and the
# release it computes from is the hand-seeded v0.2.15 baseline: delete that
# release and the next cut falls back to v0.0.0 -> v0.1.0, below the readers
# already deployed, which then never see an update at all.
#
# It takes the version from the branch name (release/N.N.N), so the number it
# writes is always the number the release ships under — never a second source
# of truth to drift. The files it owns:
#
#   version.txt                 the number the updater downloads to check for an update
#   go/main.go `const version`  what the shipped binary reports and compares against
#   tui/tutor.py VERSION        the same constant in the parity oracle
#   go/layout.go newVersions    the hand-kept two-release window behind the N
#   tui/layout.py NEW_VERSIONS  marker — oracle mirror, kept in the same step
#   tui/bin/tutor-darwin-*      rebuilt by bin/build-tui.sh, whose gate checks the
#   bin/tutor-host              three constants above agree and the allowlists match
#   content/index.json          regenerated by the freshly built binary
#
# It requires a clean tree, so the commit it makes holds exactly this bump and
# nothing else. Content changes for the release (new articles, the This version
# and Changelog prose) belong in `git-ops-2 commit` before or after this runs.
# bin/build-tui.sh runs go's tests as part of the rebuild: a failing build or
# test gate stops before anything is committed.
#
# Invoke it with `sh` rather than `./...` for the same reason install.sh gives:
# a tree that arrived as a download may have lost its execute bit.

set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)

BRANCH=$(git -C "$ROOT" branch --show-current)
case "$BRANCH" in
    release/*) ;;
    *)
        echo "release-version: run on a release/* branch — currently on '${BRANCH:-<detached>}'" >&2
        exit 1 ;;
esac
VERSION="${BRANCH#release/}"
# A grep, not a case pattern: the branch name is user-typed, so the shape
# check must be exact — three dot-separated digit runs, nothing else.
printf '%s' "$VERSION" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$' || {
    echo "release-version: branch '$BRANCH' carries no N.N.N version" >&2
    exit 1; }

if [ -n "$(git -C "$ROOT" status --porcelain --untracked-files=all)" ]; then
    echo "release-version: checkout is dirty — seal your content with git-ops-2 commit first" >&2
    exit 1
fi

echo "[1/5] version.txt <- $VERSION"
printf '%s\n' "$VERSION" > "$ROOT/version.txt"

echo "[2/5] go/main.go, tui/tutor.py, allowlists <- $VERSION"
sed -i "s/^const version = .*/const version = \"$VERSION\"/" "$ROOT/go/main.go"
sed -i "s/^VERSION = .*/VERSION = \"$VERSION\"/" "$ROOT/tui/tutor.py"

# The allowlists keep the two most recent releases: drop the oldest, add the
# one being cut. Both literals are rewritten from the same numbers, and the
# build gate re-checks them, so the reader and the oracle can never disagree
# with each other about what counts as new.
GO_LIST=$(sed -n 's/^var newVersions = \[\]string{\(.*\)}$/\1/p' "$ROOT/go/layout.go")
PY_LIST=$(sed -n 's/^NEW_VERSIONS = (\(.*\))$/\1/p' "$ROOT/tui/layout.py")
[ -n "$GO_LIST" ] && [ -n "$PY_LIST" ] || {
    echo "release-version: could not find the allowlist literals" >&2; exit 1; }
# Exactly two releases, counted by commas — wc -l would undercount a list
# with no trailing newline, so count the separators instead.
[ "$(printf '%s' "$GO_LIST" | tr -cd ',' | wc -c)" -eq 1 ] || {
    echo "release-version: go/layout.go allowlist is not two releases — edit it by hand" >&2; exit 1; }
[ "$(printf '%s' "$PY_LIST" | tr -cd ',' | wc -c)" -eq 1 ] || {
    echo "release-version: tui/layout.py allowlist is not two releases — edit it by hand" >&2; exit 1; }
GO_NEW="$(printf '%s' "$GO_LIST" | sed 's/^"[^"]*", *//'), \"v$VERSION\""
PY_NEW="$(printf '%s' "$PY_LIST" | sed 's/^"[^"]*", *//'), \"v$VERSION\""
sed -i "s/^var newVersions = \[\]string{.*}$/var newVersions = []string{$(printf '%s' "$GO_NEW" | sed 's/[&/]/\\&/g')}/" "$ROOT/go/layout.go"
sed -i "s/^NEW_VERSIONS = (.*)$/NEW_VERSIONS = ($(printf '%s' "$PY_NEW" | sed 's/[&/]/\\&/g'))/" "$ROOT/tui/layout.py"

echo "[3/5] rebuild: sh bin/build-tui.sh (gate + tests + binaries)"
sh "$ROOT/bin/build-tui.sh"

echo "[4/5] regenerate content/index.json"
"$ROOT/bin/tutor-host" index

echo "[5/5] commit + push"
git -C "$ROOT" add version.txt go/main.go go/layout.go tui/tutor.py tui/layout.py tui/bin bin/tutor-host content/index.json
git -C "$ROOT" -c user.email=taliskerpruighe@gmail.com -c user.name=taliskerpruighe \
    commit -q -m "chore(release): $VERSION"
git -C "$ROOT" push -q origin "$BRANCH"

cat <<EOF

Done.
  release: $BRANCH ($VERSION)
EOF
